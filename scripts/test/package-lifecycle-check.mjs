#!/usr/bin/env node
// Generic per-package lifecycle contract: every catalog package must enable, re-enable (idempotent),
// disable, and re-disable (idempotent) without error, and the enabled-packages registry must reflect
// the expected state after each step. Complements system-package-ownership-characterization-check.mjs
// (which hand-asserts specific Codex hook content for 2 packages) by covering every package generically
// rather than by name.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { loadPackageCatalog } from "../cli/package-catalog.mjs";
import { MULTI_SKILL_COMMAND, MULTI_SKILL_IDS, MULTI_SKILL_PACKAGE_ID, writeMultiSkillPackage } from "./fixtures/multi-skill-package.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const cli = path.join(repoRoot, "scripts/cli/main.mjs");
const uninstall = path.join(repoRoot, "scripts/install/uninstall.sh");
const generatedCommandMarker = "<!-- Generated by scripts/build/render-slash-commands.mjs; do not edit directly. -->";

function makeHome() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "roborepo-package-lifecycle-"));
  fs.mkdirSync(path.join(tmp, ".claude"), { recursive: true });
  fs.mkdirSync(path.join(tmp, ".codex"), { recursive: true });
  fs.writeFileSync(path.join(tmp, ".claude", "settings.json"), "{}");
  fs.writeFileSync(path.join(tmp, ".codex", "config.toml"), "");
  return tmp;
}

function readRegistry(tmp) {
  try {
    return JSON.parse(fs.readFileSync(path.join(tmp, ".roborepo", "enabled-packages.json"), "utf8")).packages || [];
  } catch {
    return [];
  }
}

function writeOwnedCommand(home, harness, name, packageId) {
  const commandsDir = path.join(home, `.${harness}`, "commands");
  fs.mkdirSync(commandsDir, { recursive: true });
  const target = path.join(commandsDir, `${name}.md`);
  fs.writeFileSync(target, `${generatedCommandMarker}\n<!-- Owned by package: ${packageId} -->\n\n# /${name}\n`);
  return target;
}

const packageIds = loadPackageCatalog().map((pkg) => pkg.id);
assert.ok(packageIds.length > 0, "expected at least one package in the catalog");

for (const pkgId of packageIds) {
  const tmp = makeHome();
  const env = { ...process.env, HOME: tmp, ROBOREPO_STATE_DIR: path.join(tmp, ".roborepo"), SKIP_MCP: "1" };
  try {
    const enable1 = spawnSync(process.execPath, [cli, "package", "enable", pkgId], { env, encoding: "utf8" });
    assert.equal(enable1.status, 0, `${pkgId}: enable should succeed\n${enable1.stderr}`);
    assert.ok(readRegistry(tmp).includes(pkgId), `${pkgId}: registry should list package enabled after enable`);

    const enable2 = spawnSync(process.execPath, [cli, "package", "enable", pkgId], { env, encoding: "utf8" });
    assert.equal(enable2.status, 0, `${pkgId}: re-enable should be idempotent\n${enable2.stderr}`);

    const disable1 = spawnSync(process.execPath, [cli, "package", "disable", pkgId], { env, encoding: "utf8" });
    assert.equal(disable1.status, 0, `${pkgId}: disable should succeed\n${disable1.stderr}`);
    assert.ok(!readRegistry(tmp).includes(pkgId), `${pkgId}: registry should not list package enabled after disable`);

    const disable2 = spawnSync(process.execPath, [cli, "package", "disable", pkgId], { env, encoding: "utf8" });
    assert.equal(disable2.status, 0, `${pkgId}: re-disable should be idempotent\n${disable2.stderr}`);

    const enable3 = spawnSync(process.execPath, [cli, "package", "enable", pkgId], { env, encoding: "utf8" });
    assert.equal(enable3.status, 0, `${pkgId}: re-enable after disable should succeed\n${enable3.stderr}`);
    assert.ok(readRegistry(tmp).includes(pkgId), `${pkgId}: registry should list package enabled after re-enable`);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

{
  const tmp = makeHome();
  const env = { ...process.env, HOME: tmp, ROBOREPO_STATE_DIR: path.join(tmp, ".roborepo"), SKIP_MCP: "1" };
  try {
    const staleSkillCache = path.join(tmp, ".roborepo", "skills", "vanished-package-skill");
    fs.mkdirSync(staleSkillCache, { recursive: true });
    fs.writeFileSync(path.join(staleSkillCache, ".builtin-managed"), "");
    fs.mkdirSync(path.join(tmp, ".claude", "skills"), { recursive: true });
    fs.symlinkSync(staleSkillCache, path.join(tmp, ".claude", "skills", "vanished-package-skill"));
    const staleCommand = writeOwnedCommand(tmp, "claude", "vanished-command", "vanished-package");
    fs.writeFileSync(path.join(tmp, ".claude", "commands", "user-command.md"), "user-authored\n");
    const stalePackageRuntime = path.join(tmp, ".roborepo", "package-runtime", "vanished-package", "tool.mjs");
    fs.mkdirSync(path.dirname(stalePackageRuntime), { recursive: true });
    fs.writeFileSync(stalePackageRuntime, "owned developer-runtime\n");

    const apply =spawnSync(process.execPath, [cli, "config", "apply"], { env, encoding: "utf8" });
    assert.equal(apply.status, 0, `config apply should succeed while pruning orphaned projections\n${apply.stdout}${apply.stderr}`);
    assert.ok(!fs.existsSync(staleSkillCache), "config apply removes orphaned managed skill cache entries");
    assert.ok(!fs.existsSync(path.join(tmp, ".claude", "skills", "vanished-package-skill")), "config apply removes orphaned managed skill views");
    assert.ok(!fs.existsSync(staleCommand), "config apply removes orphaned package-owned slash commands");
    assert.ok(fs.existsSync(path.join(tmp, ".claude", "commands", "user-command.md")), "config apply preserves user-authored commands");
    assert.ok(!fs.existsSync(stalePackageRuntime), "config apply removes orphaned package-runtime assets");  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

{
  const tmp = makeHome();
  const env = { ...process.env, HOME: tmp, ROBOREPO_STATE_DIR: path.join(tmp, ".roborepo"), SKIP_MCP: "1" };
  try {
    const leakedCommand = writeOwnedCommand(tmp, "claude", "leaked-command", "technical-writing");
    const preflight = spawnSync("bash", [uninstall, "--check-clean"], { env, encoding: "utf8" });
    assert.notEqual(preflight.status, 0, "remnant check must fail while an owned slash command remains");
    assert.match(preflight.stderr, /leaked-command\.md/, "remnant check reports owned slash-command remnants");

    const run = spawnSync("bash", [uninstall], { env, encoding: "utf8" });
    assert.equal(run.status, 0, `uninstall should remove owned slash commands\n${run.stdout}${run.stderr}`);
    assert.ok(!fs.existsSync(leakedCommand), "uninstall removes package-owned slash commands");
    assert.match(run.stdout, /ok: no active roborepo remnants/, "uninstall only reports clean after owned commands are gone");
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

// A package with several skills is one unit: enable installs every skill and command, removing any
// one skill's cache or command wrapper reports the whole package partial, and disable removes all
// of it. The fixture sits in a throwaway app root because only a built-in package gets generated
// command wrappers, and the real catalog must not gain a test package.
{
  const tmp = makeHome();
  const appRoot = path.join(tmp, "app");
  fs.mkdirSync(path.join(appRoot, ".git"), { recursive: true });
  for (const dir of ["manifests", "scripts", "globals/harnesses", "globals/system"]) {
    fs.cpSync(path.join(repoRoot, dir), path.join(appRoot, dir), { recursive: true });
  }
  writeMultiSkillPackage(path.join(appRoot, "globals", "packages"));
  const stateDir = path.join(tmp, ".roborepo");
  const env = { ...process.env, HOME: tmp, ROBOREPO_STATE_DIR: stateDir, ROBOREPO_APP_ROOT: appRoot, ROBOREPO_MODE: "development", SKIP_MCP: "1" };
  const run = (...args) => spawnSync(process.execPath, [cli, ...args], { env, encoding: "utf8" });
  const status = () => JSON.parse(run("package", "status", MULTI_SKILL_PACKAGE_ID, "--json").stdout).status;
  const pkgId = MULTI_SKILL_PACKAGE_ID;
  const commandPath = (harness) => path.join(tmp, `.${harness}`, "commands", `${MULTI_SKILL_COMMAND}.md`);
  try {
    const validate = run("package", "validate", pkgId);
    assert.equal(validate.status, 0, `${pkgId}: validate should pass\n${validate.stderr}`);
    const render = run("skill", "render-commands");
    assert.equal(render.status, 0, `${pkgId}: render-commands should succeed\n${render.stderr}`);

    assert.equal(run("package", "enable", pkgId).status, 0, `${pkgId}: enable should succeed`);
    for (const skillId of MULTI_SKILL_IDS) {
      assert.ok(fs.existsSync(path.join(stateDir, "skills", skillId, "SKILL.md")), `${pkgId}: enable caches ${skillId}`);
      for (const harness of ["claude", "codex"]) {
        assert.ok(fs.existsSync(path.join(tmp, `.${harness}`, "skills", skillId)), `${pkgId}: enable links ${skillId} for ${harness}`);
      }
    }
    for (const harness of ["claude", "codex"]) assert.ok(fs.existsSync(commandPath(harness)), `${pkgId}: enable installs /${MULTI_SKILL_COMMAND} for ${harness}`);
    assert.match(fs.readFileSync(path.join(tmp, ".claude", "CLAUDE.md"), "utf8"), /## Duo Suite/, `${pkgId}: enable renders its rules fragment`);
    assert.equal(status(), "enabled", `${pkgId}: every component present reads enabled`);

    fs.rmSync(path.join(stateDir, "skills", "duo-helper"), { recursive: true, force: true });
    assert.equal(status(), "partial", `${pkgId}: one missing skill cache reads partial`);
    assert.equal(run("package", "enable", pkgId).status, 0, `${pkgId}: re-enable repairs the missing skill`);
    assert.equal(status(), "enabled", `${pkgId}: re-enable restores enabled`);

    fs.rmSync(commandPath("codex"));
    assert.equal(status(), "partial", `${pkgId}: one missing command wrapper reads partial`);

    assert.equal(run("package", "disable", pkgId).status, 0, `${pkgId}: disable should succeed`);
    assert.equal(status(), "disabled", `${pkgId}: disable reads disabled`);
    for (const skillId of MULTI_SKILL_IDS) {
      assert.ok(!fs.existsSync(path.join(stateDir, "skills", skillId)), `${pkgId}: disable removes ${skillId} cache`);
      for (const harness of ["claude", "codex"]) {
        assert.ok(!fs.existsSync(path.join(tmp, `.${harness}`, "skills", skillId)), `${pkgId}: disable unlinks ${skillId} for ${harness}`);
      }
    }
    assert.ok(!fs.existsSync(commandPath("claude")), `${pkgId}: disable removes /${MULTI_SKILL_COMMAND}`);
    assert.doesNotMatch(fs.readFileSync(path.join(tmp, ".claude", "CLAUDE.md"), "utf8"), /## Duo Suite/, `${pkgId}: disable drops its rules fragment`);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

console.log(`ok: package lifecycle contract (${packageIds.length} packages, plus a several-skill package)`);