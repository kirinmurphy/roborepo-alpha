#!/usr/bin/env node
import assert from "node:assert/strict";
import { renderMarkdown } from "../cli/markdown-render.mjs";

// Regression coverage for the heading-slug, table, and mermaid-fallback extensions added for the
// Telemetry page's "view docs" popup (docs/user/guides/telemetry.md deep-linking needs stable heading
// ids; the guide itself leans on tables/mermaid instead of dense prose). These extensions are
// shared by every renderMarkdown() consumer (Config's skill-source popup, the new Telemetry guide
// route), so a regression here would silently break more than one page.

testHeadingIdsAndDedup();
testHeadingIdSlugifiesPunctuation();
testTable();
testMermaidFallback();
testPlainCodeBlockUnaffected();
testExistingFeaturesStillWork();
testHtmlCommentsDropped();
testTaskListItems();
testWrappedListItems();
const imageHtml = renderMarkdown('![Example "quoted" caption](../../images/tokens/conditions-light.png)');
assert.match(imageHtml, /<img src="\.\.\/\.\.\/images\/tokens\/conditions-light.png"/);
assert.match(imageHtml, /alt="Example &quot;quoted&quot; caption"/);
assert.doesNotMatch(renderMarkdown('![Bad](javascript:alert)\n![Bad](data:text/html,example)'), /<img/);
assert.match(renderMarkdown('`![literal](/docs/images/test.png)`'), /<code>!\[literal\]/);
console.log("markdown-render checks passed");

function testHeadingIdsAndDedup() {
  const html = renderMarkdown("# Global Filters\n\n## Time Range\n\nSome text.\n\n## Time Range\n\nMore text.\n");
  assert.match(html, /<h1 id="global-filters">Global Filters<\/h1>/);
  assert.match(html, /<h2 id="time-range">Time Range<\/h2>/);
  // Repeat heading text gets a deduped, unambiguous id — GitHub-style -1 suffix.
  assert.match(html, /<h2 id="time-range-1">Time Range<\/h2>/);
}

function testHeadingIdSlugifiesPunctuation() {
  const html = renderMarkdown("## Package Cost & Regression (exploratory)\n");
  assert.match(html, /<h2 id="package-cost--regression-exploratory">/);
  assert.match(renderMarkdown("## Step 1 — When they agree\n"), /<h2 id="step-1--when-they-agree">/);
}

function testTable() {
  const md = [
    "| Filter | What it does |",
    "| --- | --- |",
    "| Time | narrows window |",
    "| Model | narrows by model |",
    "",
  ].join("\n");
  const html = renderMarkdown(md);
  assert.match(html, /<div class="md-table-wrap"><table>/);
  assert.match(html, /<th>Filter<\/th><th>What it does<\/th>/);
  assert.match(html, /<td>Time<\/td><td>narrows window<\/td>/);
  assert.match(html, /<td>Model<\/td><td>narrows by model<\/td>/);
}

function testMermaidFallback() {
  const md = "```mermaid\nflowchart LR\n  A --> B\n```\n";
  const html = renderMarkdown(md);
  assert.match(html, /class="md-mermaid"/);
  assert.match(html, /<pre class="mermaid" data-mermaid-source="/);
  // Diagram source stays present and legible (escaped) in both the rendered element's textContent
  // and the data attribute doc-guide-modal.js reads from if mermaid.run() fails.
  assert.match(html, /flowchart LR/);
  assert.match(html, /A --&gt; B/);
}

function testPlainCodeBlockUnaffected() {
  const html = renderMarkdown("```js\nconst x = 1;\n```\n");
  assert.match(html, /<pre><code>const x = 1;<\/code><\/pre>/);
  assert.doesNotMatch(html, /md-mermaid/);
}

// Guard against regressing the renderer's existing consumers (Plans drawer's own copy is separate,
// but scripts/cli/markdown-render.mjs also backs Config's skill-source popup).
// Every generated slash-command wrapper opens with a "do not edit directly" banner and an
// "Owned by package:" marker. Those are authoring metadata: invisible in a normal markdown viewer,
// but the portal's skill popup renders this HTML, so leaving them in showed raw comment syntax to
// the reader. BEGIN/END markers are the deliberate exception -- they mark section boundaries and
// render through renderCommentLine().
function testHtmlCommentsDropped() {
  const html = renderMarkdown(
    "<!-- Generated by scripts/build/render-slash-commands.mjs; do not edit directly. -->\n" +
      "<!-- Owned by package: plan-promote -->\n\n# /plan-promote\n\nBody text.\n",
  );
  assert.doesNotMatch(html, /render-slash-commands/);
  assert.doesNotMatch(html, /Owned by package/);
  assert.doesNotMatch(html, /&lt;!--/);
  assert.match(html, /<h1 id="plan-promote">\/plan-promote<\/h1>/);
  assert.match(html, /Body text\./);

  // BEGIN/END markers survive: they are section boundaries a reader is meant to see, so the
  // drop rule must not swallow them.
  const marked = renderMarkdown("<!-- BEGIN roborepo -->\ninside\n<!-- END roborepo -->\n");
  assert.match(marked, /md-meta/);
  assert.match(marked, /BEGIN roborepo/);
  assert.match(marked, /END roborepo/);
  assert.match(marked, /inside/);
}

// Plan bodies are mostly `- [ ]` checklists, and the Plans drawer now renders through this shared
// renderer instead of its own private one — which did support checkboxes. Keeping them here is what
// makes that consolidation lossless.
function testTaskListItems() {
  const html = renderMarkdown("- [ ] open item\n- [x] done item\n- plain item\n");
  assert.match(html, /<li class="md-task"><input type="checkbox" disabled> open item<\/li>/);
  assert.match(html, /<li class="md-task"><input type="checkbox" disabled checked> done item<\/li>/);
  assert.match(html, /<li>plain item<\/li>/);
  // Inline markup inside a task item still renders.
  const inlineHtml = renderMarkdown("- [x] ship `render` and **tables**\n");
  assert.match(inlineHtml, /<code>render<\/code>/);
  assert.match(inlineHtml, /<strong>tables<\/strong>/);
}

function testWrappedListItems() {
  const html = renderMarkdown("- **first** item wraps\n  onto a second line\n- second\nafter\n");
  assert.match(html, /<ul><li><strong>first<\/strong> item wraps onto a second line<\/li><li>second<\/li><\/ul>/);
  // An unindented line still ends the list.
  assert.match(html, /<\/ul>\n<p>after<\/p>/);
}

function testExistingFeaturesStillWork() {
  const html = renderMarkdown("**bold** and `code` and [a link](https://example.com)\n\n- one\n- two\n");
  assert.match(html, /<strong>bold<\/strong>/);
  assert.match(html, /<code>code<\/code>/);
  assert.match(html, /<a href="https:\/\/example\.com"/);
  assert.match(html, /<ul><li>one<\/li><li>two<\/li><\/ul>/);
}
