#!/usr/bin/env node
// An install updated across a package rename or retirement: the registry still names packages the
// catalog no longer has (here the pre-plan-suite `plan-docs`, `wrap-up`, and `integration-check`,
// `plan-start`, which `plan-execute` replaced, and the six per-skill plan packages that became
// `plan-suite`), and their skills and slash commands are still projected into the harness homes.
//
// Runs the package steps `roborepo update` runs (scripts/install/main.sh: adopt-live, the selected
// bundles, then reconcile) against a hermetic HOME, and pins the outcome: the retired IDs leave
// both registry lists, their projections are removed, the renamed packages install, and a second
// reconcile has nothing left to do.
//
// The six plan IDs differ from the others: `plan-suite` reuses their skill IDs. adopt-live finds
// those skill caches still in place and adopts `plan-suite`, and reconcile then installs all six
// skills and re-owns their commands, so the plan skill links survive the update. An install that
// had enabled only some of the six ends with all of them.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const cli = path.join(repoRoot, "scripts/cli/main.mjs");
const OLD_PLAN_PACKAGES = ["plan-write", "plan-promote", "plan-execute", "plan-review", "plan-close", "plan-archive"];
// Enabled before the update: two of the six, so the check shows the suite arrives whole.
const ENABLED_OLD_PLAN_PACKAGES = ["plan-write", "plan-close"];
const RETIRED = ["plan-docs", "wrap-up", "integration-check", "plan-start", ...ENABLED_OLD_PLAN_PACKAGES];
// The retired packages that left a skill and slash command behind in the harness homes.
const PROJECTED = ["plan-docs", "wrap-up", "plan-start"];
const COMMAND_MARKER = "<!-- Generated by scripts/build/render-slash-commands.mjs; do not edit directly. -->";

const home = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "roborepo-retired-ids-")));
const state = path.join(home, ".roborepo");
const env = { ...process.env, HOME: home, ROBOREPO_STATE_ROOT: state, SKIP_MCP: "1", ROBOREPO_PRESETS_ONBOARD: "skip" };
for (const key of ["ROBOREPO_WORKSPACE_ROOT", "ROBOREPO_APP_ROOT"]) delete env[key];

function roborepo(...args) {
  const result = spawnSync(process.execPath, [cli, ...args], { env, encoding: "utf8" });
  assert.equal(result.status, 0, `roborepo ${args.join(" ")} failed\nstdout:\n${result.stdout}\nstderr:\n${result.stderr}`);
  return result;
}

const registryPath = path.join(state, "enabled-packages.json");
const readRegistry = () => JSON.parse(fs.readFileSync(registryPath, "utf8"));

try {
  fs.mkdirSync(path.join(home, ".claude", "commands"), { recursive: true });
  fs.mkdirSync(path.join(home, ".claude", "skills"), { recursive: true });
  fs.mkdirSync(path.join(home, ".codex"), { recursive: true });
  fs.writeFileSync(path.join(home, ".claude", "settings.json"), "{}");
  fs.writeFileSync(path.join(home, ".codex", "config.toml"), "");

  // The registry as an install left it: five retired IDs enabled (three old packages and two of the
  // six old plan packages), one explicitly disabled, next to a current package.
  fs.mkdirSync(state, { recursive: true });
  fs.writeFileSync(registryPath, `${JSON.stringify({ packages: ["plan-docs", "wrap-up", "plan-start", ...ENABLED_OLD_PLAN_PACKAGES, "session-close"], disabled: ["integration-check"] }, null, 2)}\n`);

  // What the retired packages projected: a managed skill cache entry, the Claude skill view that
  // links to it, and a generated slash command naming its owner.
  for (const id of PROJECTED) {
    const cache = path.join(state, "skills", id);
    fs.mkdirSync(cache, { recursive: true });
    fs.writeFileSync(path.join(cache, ".builtin-managed"), "");
    fs.writeFileSync(path.join(cache, "SKILL.md"), `---\nname: ${id}\ndescription: retired\n---\n`);
    fs.symlinkSync(cache, path.join(home, ".claude", "skills", id));
    fs.writeFileSync(path.join(home, ".claude", "commands", `${id}.md`), `---\ndescription: retired\n---\n\n${COMMAND_MARKER}\n<!-- Owned by package: ${id} -->\n`);
  }

  // What the two enabled plan packages projected before the move: their real skill content, the
  // Claude skill view, and a command wrapper owned by the old package ID.
  for (const id of ENABLED_OLD_PLAN_PACKAGES) {
    const cache = path.join(state, "skills", id);
    fs.cpSync(path.join(repoRoot, "globals/packages/plan-suite/skills", id), cache, { recursive: true });
    fs.writeFileSync(path.join(cache, ".builtin-managed"), "");
    fs.symlinkSync(cache, path.join(home, ".claude", "skills", id));
    fs.writeFileSync(path.join(home, ".claude", "commands", `${id}.md`), `---\ndescription: plan\n---\n\n${COMMAND_MARKER}\n<!-- Owned by package: ${id} -->\n`);
  }

  roborepo("package", "adopt-live");
  roborepo("bundle", "apply", "--selected");
  const reconcile = roborepo("package", "reconcile");

  const registry = readRegistry();
  for (const id of RETIRED) {
    assert.ok(!registry.packages.includes(id), `${id} leaves the enabled list`);
    assert.ok(!registry.disabled.includes(id), `${id} is dropped, not parked in the disabled list`);
    assert.match(reconcile.stderr, new RegExp(`remove stale package not in catalog: ${id}`), `${id} is named as removed`);
  }
  assert.ok(registry.packages.includes("session-close"), "a current package stays enabled");
  assert.ok(registry.packages.includes("plan-suite"), "adopt-live adopts plan-suite from the plan skills left in place");

  for (const id of PROJECTED) {
    assert.equal(fs.existsSync(path.join(state, "skills", id)), false, `${id}: managed skill cache removed`);
    assert.equal(fs.existsSync(path.join(home, ".claude", "skills", id)), false, `${id}: Claude skill view removed`);
    assert.equal(fs.existsSync(path.join(home, ".claude", "commands", `${id}.md`)), false, `${id}: slash command removed`);
  }
  const planSuiteInstalled = (when) => {
    for (const harness of [".claude", ".codex", ".gemini"]) {
      for (const id of OLD_PLAN_PACKAGES) {
        assert.ok(fs.existsSync(path.join(home, harness, "skills", id, "SKILL.md")), `${when}: ${harness} ${id} skill is installed`);
        const command = path.join(home, harness, "commands", `${id}.md`);
        assert.ok(fs.existsSync(command), `${when}: ${harness} /${id} is installed`);
        assert.match(fs.readFileSync(command, "utf8"), /Owned by package: plan-suite/, `${when}: ${harness} /${id} is owned by plan-suite`);
      }
    }
  };
  planSuiteInstalled("after update");

  const again = roborepo("package", "reconcile");
  assert.doesNotMatch(again.stderr, /stale package/, "a second reconcile finds nothing stale");
  assert.deepEqual(readRegistry().packages, registry.packages, "and leaves the registry unchanged");

  roborepo("package", "enable", "plan-suite");
  planSuiteInstalled("after enable plan-suite");

  // The update script runs these steps in this order; if it stops reconciling, this test no longer
  // describes `roborepo update`.
  const install = fs.readFileSync(path.join(repoRoot, "scripts/install/main.sh"), "utf8");
  const steps = ["package adopt-live", "bundle apply --selected", "package reconcile"].map((step) => install.indexOf(`main.mjs" ${step}`));
  assert.ok(steps.every((at, i) => at > 0 && (i === 0 || at > steps[i - 1])), "scripts/install/main.sh runs adopt-live, the selected bundles, then reconcile");
} finally {
  fs.rmSync(home, { recursive: true, force: true });
}

console.log("ok: retired package ids are dropped and their projections removed on update");
