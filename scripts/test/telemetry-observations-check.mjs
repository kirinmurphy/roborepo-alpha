import assert from "node:assert/strict";
import { normalizeObservations, normalizeTokenUsage, evaluateCondition, aggregateCondition } from "../cli/telemetry-observations.mjs";
const usage = { input: 100, output: 20, cache_read: 30, cache_creation: 10, total: 160 };
const row = (session, extra = {}) => ({ schema: 3, harness: "claude", session_id: session, call_id: "call1", capture_id: `capture-${session}`, ts: "2026-09-01T00:00:00Z", tokens: usage, session: { model: "model-a" }, repo: { repository_id: "git:one", label: "same" }, ...extra });
const original = row("one");
const mirrored = { ...original, event: "PostToolUse", capture_id: "mirror" };
const events = [original, mirrored, original, row("two", { harness: "codex" }), row("one", { harness: "codex" }), row("fallback", { call_id: null, capture_id: null })];
const normalized = normalizeObservations(events);
assert.equal(normalized.flows.length, 4);
assert.equal(normalized.sessions.length, 4);
assert.equal(normalized.fallback_flows, 1);
assert.deepEqual(normalized, normalizeObservations([...events].reverse()));
assert.ok(normalized.flows.every((flow) => flow.tokens === null));
assert.equal(normalized.sessions.find((session) => session.harness === "claude" && session.session_id === "one").tokens.total, 160);
assert.equal(normalizeTokenUsage(usage).input, 140);
for (const invalid of [-1, 0.5, Infinity, NaN, Number.MAX_SAFE_INTEGER + 1, "5"]) assert.equal(normalizeTokenUsage({ ...usage, input: invalid }), null);
assert.equal(normalizeTokenUsage({ ...usage, input: Number.MAX_SAFE_INTEGER }), null);
assert.equal(normalizeTokenUsage({ total: 2 }), null);
assert.equal(normalizeTokenUsage({ ...usage, total: 200 }).total_override, true);
assert.equal(normalizeObservations([original, { ...mirrored, tokens: { ...usage, total: 200 } }]).sessions[0].tokens, null);
assert.equal(normalizeObservations([original, { ...mirrored, session: { model: "other" } }]).sessions[0].model, null);
const snapshot = { schema: 2, snapshot_id: "snapshot", harness: "codex", packages: ["enabled"], skills: [], rules: [], evaluability: { packages: true, skills: true } };
const observation = normalizeObservations([row("one", { config_snapshot_id: "snapshot" })]).sessions[0];
assert.equal(evaluateCondition(observation, { dimension: "packages", value: "enabled" }, [snapshot]).state, "present");
assert.equal(evaluateCondition(observation, { dimension: "packages", value: "disabled" }, [snapshot]).state, "absent");
assert.equal(evaluateCondition(observation, { dimension: "rules", value: "missing" }, [snapshot]).state, "unknown");
assert.equal(evaluateCondition(observation, { dimension: "packages", value: "enabled" }, []).state, "unknown");
assert.equal(evaluateCondition(observation, { dimension: "packages", value: "enabled" }, [{ ...snapshot, unavailable: ["packages"] }]).state, "unknown");
assert.equal(evaluateCondition(normalizeObservations([row("legacy", { repo: { label: "same" } })]).sessions[0], { dimension: "repo", value: "git:one" }).state, "unknown");
const cohorts = Array.from({ length: 78 }, (_, index) => ({ ...observation, id: `s${index}`, model: index < 12 ? "with" : index < 76 ? "without" : null }));
const affected = new Set([...cohorts.slice(0, 3), ...cohorts.slice(12, 44)].map((item) => item.id));
const result = aggregateCondition(cohorts, { dimension: "model", value: "with" }, affected);
assert.equal(result.with_rate, 0.25);
assert.equal(result.without_rate, 0.5);
assert.equal(result.relative_delta, -0.5);
assert.equal(result.unknown_condition, 2);
assert.equal(result.coverage, 76 / 78);
assert.deepEqual(result, aggregateCondition([...cohorts, ...cohorts].reverse(), { dimension: "model", value: "with" }, affected));
assert.equal(aggregateCondition(cohorts.slice(76), { dimension: "model", value: "with" }, affected).with_rate, null);
assert.equal(aggregateCondition(cohorts, { dimension: "model", value: "with" }, new Set()).relative_delta, null);
assert.equal(aggregateCondition(cohorts.slice(0, 12), { dimension: "model", value: "with" }, affected).comparison_available, false);
console.log("telemetry observations: identity, dedupe, evaluability, cohorts, token normalization and reorder checks passed");

const missingIdentity = normalizeObservations([row("missing", { harness: null, session_id: null })]);
assert.equal(missingIdentity.sessions.length, 0, "unidentified captures are not independent sessions");
assert.equal(missingIdentity.unidentified_sessions, 1);
assert.equal(missingIdentity.flows.length, 1);
assert.equal(normalizeObservations([row("old", { schema: undefined }), row("v2", { schema: 2 })]).sessions.length, 0, "captures without the current schema are not observed");
assert.equal(evaluateCondition(observation, { dimension: "revision", value: "future-revision" }, [snapshot]).state, "unknown");
