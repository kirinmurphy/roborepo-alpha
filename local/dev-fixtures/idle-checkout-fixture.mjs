// Live fixture for an idle repository whose worktree has disappeared — the "checkout missing" row.
//
// WHY THIS EXISTS: Runtime only reports a checkout's on-disk state for a repository with nothing
// running. Those rows come from the repository registry (the checkouts Runtime saw while they ran)
// and modules/repositories/lifecycle.mjs inspecting each recorded path. A running repository lists
// only the checkouts with live processes, and a process cannot run in a directory that is gone, so
// this case cannot live in multi-member-fixture.mjs.
//
// THE SHAPE: one repository with a main checkout on main and one linked worktree on
// `missing-checkout`. Start records both checkouts in the registry, with the same fields Runtime
// records when it sees a listener in each, then deletes the worktree's directory. Nothing is left
// running, so the card is idle: the main row is present and the worktree row reads "checkout
// missing".
//
// Start recreates the worktree each time (pruning the stale git registration first), so the
// deletion is repeatable. The fixture lives beside the others under ~/projects/prototypin, and its
// example.com remote gives it the "mock" badge.
//
// Driven by developer-runtime-test-data.mjs, which runs this alongside the other fixtures.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { realpathOf, rootId } from "../../modules/repositories/index.mjs";
import { recordRepositoryDiscovery } from "../../scripts/cli/repositories.mjs";

const PARENT = path.join(os.homedir(), "projects", "prototypin");
const FIXTURE_ROOT = path.join(PARENT, "idle-checkout-fixture");
const MISSING_WORKTREE = `${FIXTURE_ROOT}-wt-missing`;
const MISSING_BRANCH = "missing-checkout";
const REPOSITORY_ID = "git:github.com/example/idle-checkout-fixture";
const REMOTE = "https://github.com/example/idle-checkout-fixture.git";

const README = `# idle-checkout-fixture

Generated by \`node local/dev-fixtures/developer-runtime-test-data.mjs start\` in the roborepo dev checkout.

An idle repository whose linked worktree (\`idle-checkout-fixture-wt-missing\`) was deleted after
Runtime recorded it, so the Runtime and Home cards show a "checkout missing" row. Nothing runs here.

Not a real project. Safe to delete — the \`start\` command rebuilds it.
`;

const run = (cmd, args, cwd) => spawnSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const git = (args, cwd = FIXTURE_ROOT) => run("git", args, cwd);

// Start writes files, resets git state, and deletes a directory at fixed paths under the user's
// home, so each existing path must be provably the fixture's own first. FIXTURE_ROOT is ours when it
// is absent, an empty directory, or a repository whose origin is the fixture remote; MISSING_WORKTREE
// is ours when it is absent or a worktree sharing FIXTURE_ROOT's git directory.
function ownsFixtureRoot() {
  if (!fs.existsSync(FIXTURE_ROOT)) return true;
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) return fs.readdirSync(FIXTURE_ROOT).length === 0;
  return git(["remote", "get-url", "origin"]).stdout.trim() === REMOTE;
}

function ownsMissingWorktree() {
  if (!fs.existsSync(MISSING_WORKTREE)) return true;
  const common = run("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], MISSING_WORKTREE).stdout.trim();
  return Boolean(common) && realpathOf(common) === realpathOf(path.join(FIXTURE_ROOT, ".git"));
}

function provision() {
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) {
    fs.mkdirSync(FIXTURE_ROOT, { recursive: true });
    git(["init", "-q", "-b", "main", "."]);
    git(["remote", "add", "origin", REMOTE]);
  }
  fs.writeFileSync(path.join(FIXTURE_ROOT, "README.md"), README);
  git(["add", "README.md"]);
  const env = { ...process.env, GIT_AUTHOR_NAME: "roborepo fixture", GIT_AUTHOR_EMAIL: "fixture@example.com", GIT_COMMITTER_NAME: "roborepo fixture", GIT_COMMITTER_EMAIL: "fixture@example.com" };
  const tree = git(["write-tree"]).stdout.trim();
  const commit = spawnSync("git", ["commit-tree", tree, "-m", "Start the idle fixture"], { cwd: FIXTURE_ROOT, env, encoding: "utf8" }).stdout.trim();
  for (const branch of ["main", MISSING_BRANCH]) {
    git(["update-ref", `refs/heads/${branch}`, commit]);
    git(["update-ref", `refs/remotes/origin/${branch}`, commit]);
    git(["config", `branch.${branch}.remote`, "origin"]);
    git(["config", `branch.${branch}.merge`, `refs/heads/${branch}`]);
  }
  git(["symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/main"]);
  git(["symbolic-ref", "HEAD", "refs/heads/main"]);
  git(["reset", "-q", "--hard"]);
  // The worktree directory was deleted by the previous start; drop git's stale record of it so the
  // branch can be checked out again.
  git(["worktree", "prune"]);
  if (!fs.existsSync(MISSING_WORKTREE)) git(["worktree", "add", "-q", MISSING_WORKTREE, MISSING_BRANCH]);
}

// Records each checkout as Runtime would have on seeing a listener in it: same repository id, the
// rootId derived from the checkout's realpath, and that path. Must run while the worktree exists,
// since the realpath is what the rootId is derived from.
function recordCheckouts() {
  for (const [checkoutPath, localRootKind] of [[FIXTURE_ROOT, "clone"], [MISSING_WORKTREE, "worktree"]]) {
    const realpath = realpathOf(checkoutPath);
    recordRepositoryDiscovery({
      repositoryId: REPOSITORY_ID,
      kind: "git",
      displayName: "idle-checkout-fixture",
      source: "developer-runtime",
      evidence: "git-remote",
      confidence: "high",
      localRoot: rootId(realpath),
      localRootKind,
      localRootPath: realpath,
    });
  }
}

export function startIdleCheckoutFixture() {
  if (run("git", ["--version"]).status !== 0) return { ok: false, message: "git is unavailable" };
  if (!ownsFixtureRoot()) return { ok: false, message: `idle-checkout fixture: ${FIXTURE_ROOT} exists and is not the fixture's repository; refusing to touch it` };
  if (!ownsMissingWorktree()) return { ok: false, message: `idle-checkout fixture: ${MISSING_WORKTREE} exists and is not the fixture's worktree; refusing to touch it` };
  provision();
  // Re-checked after provisioning: the delete below must only ever remove the worktree git just
  // created for this fixture.
  if (!ownsMissingWorktree()) return { ok: false, message: `idle-checkout fixture: ${MISSING_WORKTREE} is not the fixture's worktree; not deleting it` };
  recordCheckouts();
  fs.rmSync(MISSING_WORKTREE, { recursive: true, force: true });
  return `idle-checkout fixture provisioned (${FIXTURE_ROOT}; ${path.basename(MISSING_WORKTREE)} recorded, then deleted)`;
}

// Nothing runs, so there is nothing to stop; the checkout is kept like the other fixtures'.
export function stopIdleCheckoutFixture() {
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) return "idle-checkout fixture: nothing provisioned";
  return `idle-checkout fixture: nothing running; checkout kept at ${FIXTURE_ROOT}`;
}

export function statusIdleCheckoutFixture() {
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) return "idle-checkout fixture: not provisioned";
  return fs.existsSync(MISSING_WORKTREE)
    ? `idle-checkout fixture: provisioned, but ${path.basename(MISSING_WORKTREE)} exists — run start again`
    : `idle-checkout fixture: idle, ${path.basename(MISSING_WORKTREE)} missing (${FIXTURE_ROOT})`;
}
