#!/usr/bin/env node
// Live fixture for Runtime's shared-Compose-ownership verdict.
//
// WHY THIS EXISTS: the classifier's "shared" path cannot be exercised by the repositories on a
// normal machine — each has exactly one checkout, so every real stack classifies "owned". The shape
// it needs is one repository with TWO checkouts and ONE stack bind mounting both. That has to be
// built on purpose. The first version was assembled by hand in an mktemp dir and vanished when /tmp
// was cleared, taking the only reproduction of the shared verdict with it.
//
// WHY IT LIVES IN local/ AND NOT AS A PACKAGE: this is a development tool, not a product feature.
// package.json's `files` publishes globals/ and scripts/cli/ to npm, so a fixture that shells out to
// Docker would ship to every end user and appear in `roborepo package list` — a menu entry nobody
// installing roborepo has any use for. local/ is tracked in git but excluded from `files`, so this
// exists when you work from the dev checkout and simply is not there in an npm install.
//
// LOCATION OF THE FIXTURE ITSELF: under ~/projects/prototypin, not a temp dir — surviving a reboot
// is the entire point.
//
// STOP DOES NOT DELETE: `docker compose down` runs, but the checkouts stay. They are a git working
// tree that may have been edited, and deleting one to turn a fixture off is a destructive default.
// Removal is deliberate and manual; the path is printed so it is easy to do by hand.
//
// Usage (from the dev checkout) — prefer the CLI, which is the same script underneath:
//   roborepo dev fixture start|stop|status   (or `roborepo dev start` for fixture + portal)
//
// Direct invocation still works and is what the CLI shells out to:
//   node local/dev-fixtures/developer-runtime-test-data.mjs start
//   node local/dev-fixtures/developer-runtime-test-data.mjs stop
//   node local/dev-fixtures/developer-runtime-test-data.mjs status

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
// The second fixture: plain Node servers across a repository and two worktrees, for the checkout-row
// cases the Compose stack cannot show (several process members, a failing app, an API-only checkout).
import { startMultiMemberFixture, statusMultiMemberFixture, stopMultiMemberFixture } from "./multi-member-fixture.mjs";
import { startIdleCheckoutFixture, statusIdleCheckoutFixture, stopIdleCheckoutFixture } from "./idle-checkout-fixture.mjs";

const FIXTURE_ROOT = path.join(os.homedir(), "projects", "prototypin", "shared-stack-fixture");
// The second checkout is the first path plus a "-wt" suffix on purpose: it doubles as the
// sibling-prefix trap, where a naive parent-directory test would wrongly read
// ".../shared-stack-fixture-wt" as living inside ".../shared-stack-fixture".
const WORKTREE_ROOT = `${FIXTURE_ROOT}-wt`;
// Loopback-bound and high, so the fixture can never contend with a real service or be reachable off
// the machine. It is a discovery fixture, not something to browse.
const HOST_PORT = 48080;
const REMOTE = "https://github.com/example/shared-stack-fixture.git";

const COMPOSE_FILE = `# Generated by local/dev-fixtures/developer-runtime-test-data.mjs.
# One repository, two checkouts, one stack mounting both — the shape that makes Runtime's
# Compose-ownership classifier return "shared" instead of "owned".
#
# Paths are relative to this file so the stack moves with the repo rather than depending on an
# absolute path that only existed on one machine.
services:
  shared-stack-fixture:
    image: nginx:alpine
    container_name: shared-stack-fixture
    ports:
      - "127.0.0.1:${HOST_PORT}:80"
    volumes:
      # Served content. Without this nginx answers with its stock "Welcome to nginx!" page, which is
      # what Runtime would then show as the card's title — a fixture indistinguishable from any
      # stray nginx container on the machine.
      - ./public:/usr/share/nginx/html:ro
      # The two checkouts. These are what the Compose-ownership classifier actually inspects, mounted
      # read-only because nothing here should ever write back into a git working tree.
      - ./:/checkouts/primary:ro
      - ../shared-stack-fixture-wt:/checkouts/second:ro
`;

const README = `# shared-stack-fixture

Generated by \`node local/dev-fixtures/developer-runtime-test-data.mjs start\` in the roborepo dev checkout.

One repository, two checkouts, one Compose stack bind mounting both. This is the shape that
exercises Runtime's shared-Compose-ownership verdict; no ordinary repository on a dev machine
has it, because each has a single checkout and therefore always classifies as "owned".

Not a real project. Safe to delete — the \`start\` command rebuilds it.
`;

// The <title> matters beyond decoration: Runtime's HTTP probe reads it to decide a listener is a
// real page rather than infrastructure (see isEntrypoint in modules/developer-runtime/snapshot.mjs), and
// it becomes the card's label. It says what this is and how to stop it, so the fixture explains
// itself to whoever finds it running months from now.
const INDEX_HTML = `<!doctype html>
<meta charset="utf-8">
<title>Runtime test fixture — shared Compose stack</title>
<style>
  :root { color-scheme: light dark; }
  body { font: 15px/1.6 system-ui, sans-serif; max-width: 44rem; margin: 3rem auto; padding: 0 1.5rem; }
  code { background: color-mix(in srgb, currentColor 12%, transparent); padding: .1em .35em; border-radius: 3px; }
  .note { opacity: .75; font-size: .9em; }
</style>
<h1>Runtime test fixture</h1>
<p>
  This is not a real application. It is a deliberately built shape: <strong>one repository with two
  checkouts, and one Compose stack bind mounting both</strong>.
</p>
<p>
  Runtime's Compose-ownership classifier returns <code>shared</code> for this. No ordinary
  repository produces that verdict, because each has a single checkout and therefore always
  classifies as <code>owned</code> — which is why this fixture has to exist to exercise the path.
</p>
<p class="note">
  Started with <code>node local/dev-fixtures/developer-runtime-test-data.mjs start</code>.
  Stop it with <code>… stop</code>, which leaves the checkouts on disk.
</p>
`;

const run = (cmd, args, cwd) =>
  spawnSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

const git = (args, cwd = FIXTURE_ROOT) => run("git", args, cwd);

// Compose is addressed by file rather than by cwd so the caller's directory never decides which
// stack is affected.
const compose = (args) =>
  run("docker", ["compose", "-f", path.join(FIXTURE_ROOT, "docker-compose.yml"), ...args], FIXTURE_ROOT);

const lastLine = (text) => (text || "").trim().split("\n").pop();

function provision() {
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) {
    fs.mkdirSync(FIXTURE_ROOT, { recursive: true });
    git(["init", "-q", "."]);
    // A remote is what gives the fixture a stable repository identity for Runtime to group by.
    // The example.com-style URL is deliberately unfetchable: this repo must never be confused for
    // something with a real upstream.
    git(["remote", "add", "origin", REMOTE]);
  }

  fs.writeFileSync(path.join(FIXTURE_ROOT, "README.md"), README);
  fs.writeFileSync(path.join(FIXTURE_ROOT, "docker-compose.yml"), COMPOSE_FILE);
  fs.mkdirSync(path.join(FIXTURE_ROOT, "public"), { recursive: true });
  fs.writeFileSync(path.join(FIXTURE_ROOT, "public", "index.html"), INDEX_HTML);
  git(["add", "-A"]);
  // Identity is passed per-command so provisioning never depends on, or writes to, global git config.
  git(["-c", "user.email=fixture@example.com", "-c", "user.name=roborepo fixture",
    "commit", "-q", "-m", "Shared-stack fixture: one repo, two checkouts, one stack"]);

  if (!fs.existsSync(WORKTREE_ROOT)) {
    // -B so restarting after a manual `git worktree remove` does not fail on a branch that still
    // exists in the repo.
    git(["worktree", "add", "-B", "second-checkout", WORKTREE_ROOT, "HEAD"]);
  }
}

function startComposeFixture() {
  if (run("docker", ["info"]).status !== 0) return { ok: false, message: "Docker is not running — start it and retry" };
  if (run("git", ["--version"]).status !== 0) return { ok: false, message: "git is unavailable" };

  provision();

  const up = compose(["up", "-d"]);
  if (up.status !== 0) {
    return { ok: false, message: `provisioned ${FIXTURE_ROOT}, but the stack failed to start (${lastLine(up.stderr)})` };
  }
  return `fixture running on http://127.0.0.1:${HOST_PORT} (${FIXTURE_ROOT} + -wt)`;
}

function stopComposeFixture() {
  if (!fs.existsSync(path.join(FIXTURE_ROOT, "docker-compose.yml"))) return "nothing provisioned";
  const down = compose(["down"]);
  // A wedged container (Docker holding state for namespaces that no longer exist) fails here, and
  // the only remedy is restarting the daemon. Reported as a failure rather than a message so a
  // script that tears down and then rebuilds does not proceed against a stack still holding its port.
  if (down.status !== 0) return { ok: false, message: `could not stop the stack (${lastLine(down.stderr)})` };
  return `stack stopped; checkouts kept at ${FIXTURE_ROOT}`;
}

function statusComposeFixture() {
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) return "not provisioned";
  const ps = compose(["ps", "--quiet"]);
  const running = ps.status === 0 && (ps.stdout || "").trim().length > 0;
  return running
    ? `running on http://127.0.0.1:${HOST_PORT} (${FIXTURE_ROOT} + -wt)`
    : `provisioned but stopped (${FIXTURE_ROOT})`;
}

// Every action covers every fixture. Each result is either a string or { ok: false, message }; the
// combined result fails if any part did, and reports all of them either way.
function all(...actions) {
  const results = actions.map((action) => action());
  const ok = results.every((result) => typeof result === "string" || result.ok !== false);
  const message = results.map((result) => (typeof result === "string" ? result : result.message)).join("\n");
  return ok ? message : { ok: false, message };
}

const start = () => all(startComposeFixture, startMultiMemberFixture, startIdleCheckoutFixture);
const stop = () => all(stopComposeFixture, stopMultiMemberFixture, stopIdleCheckoutFixture);
const status = () => all(statusComposeFixture, statusMultiMemberFixture, statusIdleCheckoutFixture);

const ACTIONS = { start, stop, status };
const action = process.argv[2];

if (!ACTIONS[action]) {
  console.error("usage: node local/dev-fixtures/developer-runtime-test-data.mjs <start|stop|status>");
  process.exit(2);
}

// An action returns either a plain string (success) or { ok: false, message } for a failure that
// must reach the caller's exit code. Everything used to return a string and fall off the end at
// exit 0, so `dev stop` reported "could not stop the stack" and still looked successful to any
// script that checked $? — the failure was visible to a human reading output and to nothing else.
const result = ACTIONS[action]();
const ok = typeof result === "string" || result.ok !== false;
const message = typeof result === "string" ? result : result.message;

if (ok) {
  console.log(`developer-runtime test data: ${message}`);
} else {
  console.error(`developer-runtime test data: ${message}`);
  process.exit(1);
}
